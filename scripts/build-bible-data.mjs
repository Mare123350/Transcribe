// Downloads public-domain Bible texts and writes them to data/ in the app's format.
// Only markup and whitespace are touched: the words come straight from the source.
// Also regenerates shared/versification.js, the verse-count table the detector uses.
import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

const USFM = ['GEN','EXO','LEV','NUM','DEU','JOS','JDG','RUT','1SA','2SA','1KI','2KI','1CH','2CH','EZR','NEH','EST','JOB','PSA','PRO','ECC','SNG','ISA','JER','LAM','EZK','DAN','HOS','JOL','AMO','OBA','JON','MIC','NAM','HAB','ZEP','HAG','ZEC','MAL','MAT','MRK','LUK','JHN','ACT','ROM','1CO','2CO','GAL','EPH','PHP','COL','1TH','2TH','1TI','2TI','TIT','PHM','HEB','JAS','1PE','2PE','1JN','2JN','3JN','JUD','REV'];
const WEB_FILES = ['genesis','exodus','leviticus','numbers','deuteronomy','joshua','judges','ruth','1samuel','2samuel','1kings','2kings','1chronicles','2chronicles','ezra','nehemiah','esther','job','psalms','proverbs','ecclesiastes','songofsolomon','isaiah','jeremiah','lamentations','ezekiel','daniel','hosea','joel','amos','obadiah','jonah','micah','nahum','habakkuk','zephaniah','haggai','zechariah','malachi','matthew','mark','luke','john','acts','romans','1corinthians','2corinthians','galatians','ephesians','philippians','colossians','1thessalonians','2thessalonians','1timothy','2timothy','titus','philemon','hebrews','james','1peter','2peter','1john','2john','3john','jude','revelation'];

const KJV_BASE = 'https://raw.githubusercontent.com/aruljohn/Bible-kjv/master/';
const WEB_BASE = 'https://raw.githubusercontent.com/TehShrike/world-english-bible/master/json/';

async function getJson(url) {
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${url}: HTTP ${res.status}`);
  return res.json();
}

const clean = (text) => text.replace(/\s+/g, ' ').trim();

// { GEN: [ ["In the beginning...", ...verses of chapter 1], ...chapters ], ... }
async function buildKjv() {
  const names = await getJson(`${KJV_BASE}Books.json`);
  if (names.length !== 66) throw new Error('KJV: expected 66 books');
  const books = {};
  for (const [b, name] of names.entries()) {
    const book = await getJson(`${KJV_BASE}${encodeURIComponent(name.replaceAll(' ', ''))}.json`);
    books[USFM[b]] = book.chapters.map((chapter) => {
      chapter.verses.forEach((v, i) => {
        if (Number(v.verse) !== i + 1) throw new Error(`KJV: gap at ${USFM[b]} ${chapter.chapter}:${v.verse}`);
      });
      return chapter.verses.map((v) => clean(v.text));
    });
  }
  return books;
}

async function buildWeb() {
  const books = {};
  for (const [b, file] of WEB_FILES.entries()) {
    const items = await getJson(`${WEB_BASE}${file}.json`);
    const chapters = [];
    for (const item of items) {
      if (item.chapterNumber == null || item.verseNumber == null || !item.value) continue;
      const verses = (chapters[item.chapterNumber - 1] ??= []);
      verses[item.verseNumber - 1] = `${verses[item.verseNumber - 1] ?? ''} ${item.value}`;
    }
    // The WEB omits a few verses (e.g. Acts 8:37), which the source leaves blank. Blanks stay in
    // place so later verse numbers line up, but trailing ones don't count towards the chapter length.
    books[USFM[b]] = Array.from(chapters, (verses) => {
      const texts = Array.from(verses ?? [], (text) => clean(text ?? ''));
      while (texts.length && !texts.at(-1)) texts.pop();
      return texts;
    });
  }
  return books;
}

function stats(books) {
  const chapters = Object.values(books).flat();
  return { books: Object.keys(books).length, chapters: chapters.length, verses: chapters.flat().length };
}

const kjv = await buildKjv();
const web = await buildWeb();
console.log('KJV', stats(kjv));
console.log('WEB', stats(web));

await writeFile(join(root, 'data/kjv.json'), JSON.stringify({ source: KJV_BASE, books: kjv }));
await writeFile(join(root, 'data/web.json'), JSON.stringify({ source: WEB_BASE, books: web }));

const table = Object.entries(kjv)
  .map(([id, chapters]) => `  "${id}": [${chapters.map((c) => c.length).join(',')}],`)
  .join('\n');
await writeFile(
  join(root, 'shared/versification.js'),
  `// Generated by scripts/build-bible-data.mjs from the KJV. Verses per chapter, by USFM book id.\nexport const CANONICAL_VERSIFICATION = {\n${table}\n};\n`,
);
